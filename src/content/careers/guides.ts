/**
 * Practice sections live at /practice/<id>/. The last three ids are being added to the
 * taxonomy separately; the union keeps these guides valid before and after that lands.
 */
export type PracticeTopicId = TopicId | "capital-markets" | "industries" | "restructuring";

const NEW_TOPIC_LABELS: Record<string, string> = {
  "capital-markets": "Capital Markets",
  industries: "Industries",
  restructuring: "Restructuring",
};

export function practiceTopicLabel(id: PracticeTopicId): string {
  return (TOPICS as Partial<Record<string, { label: string }>>)[id]?.label ?? NEW_TOPIC_LABELS[id] ?? id;
}

